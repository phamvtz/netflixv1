function detectLang() {
  const saved = localStorage.getItem('ui_lang');
  if (saved === 'en' || saved === 'vi') return saved;
  const nav = (navigator.language || '').toLowerCase();
  return nav.startsWith('vi') ? 'vi' : 'en';
}

let currentLang = detectLang();

function t(key, vars) {
  let s = STR[currentLang]?.[key] ?? STR.en[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(vars[k]));
    });
  }
  return s;
}

function applyDom() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const html = el.getAttribute('data-i18n-html') === '1';
    const val = t(key);
    if (html) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  const titleKey = document.body.getAttribute('data-i18n-title');
  if (titleKey) document.title = t(titleKey);
  document.querySelectorAll('.lang-switch [data-lang]').forEach((btn) => {
    btn.classList.toggle('is-active', btn.dataset.lang === currentLang);
    btn.setAttribute('aria-pressed', btn.dataset.lang === currentLang ? 'true' : 'false');
  });
}

function mountSwitcher(container) {
  if (!container) return;
  container.classList.add('lang-switch');
  container.innerHTML = `
    <button type="button" data-lang="en" aria-label="English">${t('lang.en')}</button>
    <button type="button" data-lang="vi" aria-label="Tiếng Việt">${t('lang.vi')}</button>`;
  container.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
  applyDom();
}

function setLang(lang) {
  if (lang !== 'en' && lang !== 'vi') return;
  currentLang = lang;
  localStorage.setItem('ui_lang', lang);
  applyDom();
  document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
}

function getLang() {
  return currentLang;
}

function sellerMeta(view) {
  const m = SELLER_META[currentLang] || SELLER_META.en;
  return m[view] || m.orders;
}

function adminStatLabels() {
  return ADMIN_STATS[currentLang] || ADMIN_STATS.en;
}

function chip(id, key) {
  return { id, label: t(key) };
}

